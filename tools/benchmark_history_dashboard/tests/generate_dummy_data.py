#!/usr/bin/env python3
"""Generate nightly benchmark inputs for local publisher testing."""

from __future__ import annotations

import argparse
import json
import random
import shutil
import sys
from pathlib import Path


FIXTURE_MARKER = ".benchmark-history-dashboard-fixture"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-root", type=Path, required=True)
    parser.add_argument("--seed", type=int)
    parser.add_argument("--force", action="store_true")
    return parser.parse_args()


def metric(rng: random.Random, name: str, base: float, unit: str, extra: str) -> dict:
    return {
        "name": name,
        "value": round(base * rng.uniform(0.96, 1.04), 2),
        "unit": unit,
        "extra": extra,
    }


def write_results(root: Path, relative: str, results: list[dict]) -> None:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")


def main() -> int:
    args = parse_args()
    output_root = args.output_root.resolve()
    if output_root.exists() and any(output_root.iterdir()):
        if not args.force:
            print(
                f"ERROR: {output_root} is not empty; pass --force to replace it",
                file=sys.stderr,
            )
            return 1
        if not (output_root / FIXTURE_MARKER).is_file():
            print(
                f"ERROR: refusing to replace unmarked directory {output_root}",
                file=sys.stderr,
            )
            return 1
        shutil.rmtree(output_root)
    output_root.mkdir(parents=True, exist_ok=True)
    (output_root / FIXTURE_MARKER).write_text(
        "Generated by tools/benchmark_history_dashboard/tests/generate_dummy_data.py\n",
        encoding="utf-8",
    )

    rng = random.Random(args.seed)
    write_results(
        output_root,
        "syslog/results.json",
        [
            metric(
                rng,
                "cpu_percentage_normalized_avg",
                38,
                "%",
                "Nightly - Syslog/OTAP-SYSLOG - CPU % (Normalized)",
            ),
            metric(
                rng,
                "ram_mib_avg",
                210,
                "MiB",
                "Nightly - Syslog/OTAP-SYSLOG - RAM (MiB)",
            ),
        ],
    )
    write_results(
        output_root,
        "filter/dfe/results.json",
        [
            metric(
                rng,
                "cpu_percentage_normalized_avg",
                42,
                "%",
                "Nightly - Filter/OTLP-FILTER-OTLP - CPU % (Normalized)",
            )
        ],
    )
    write_results(
        output_root,
        "filter/otelcol/results.json",
        [
            metric(
                rng,
                "cpu_percentage_normalized_avg",
                67,
                "%",
                "Nightly - OTel Collector/OTLP-FILTER-OTLP (Go Collector) - CPU % (Normalized)",
            )
        ],
    )
    write_results(
        output_root,
        "clickhouse/results.json",
        [
            metric(
                rng,
                "logs_produced_rate",
                500_000,
                "logs/sec",
                "Nightly - ClickHouse/DFE - Log Throughput",
            ),
            metric(
                rng,
                "log_rows_written_rate",
                498_000,
                "rows/sec",
                "Nightly - ClickHouse/DFE - ClickHouse Throughput",
            ),
            metric(
                rng,
                "cpu_percentage_normalized_avg",
                61,
                "%",
                "Nightly - ClickHouse/DFE - CPU % (Normalized)",
            ),
        ],
    )
    write_results(
        output_root,
        "scaling-efficiency/results.json",
        [
            metric(
                rng,
                "average_scaling_efficiency",
                0.91,
                "ratio",
                "Average scaling efficiency",
            )
        ],
    )
    write_results(
        output_root,
        "passthrough/results.json",
        [
            metric(
                rng,
                "logs_received_rate",
                750_000,
                "logs/sec",
                "Continuous Passthrough/OTAP - Log Throughput",
            )
        ],
    )
    print(f"Generated benchmark inputs under {output_root}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
